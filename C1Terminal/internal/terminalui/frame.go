// Package terminalui renders a 49-column terminal on the MP-D261 e-paper panel.
package terminalui

import (
	"fmt"

	"github.com/hinshun/vt10x"
)

const (
	Width       = 296
	Height      = 152
	Columns     = 49
	Rows        = 18
	stripHeight = 8
	FrameBytes  = Width * (Height / stripHeight)
)

const (
	attrReverse   = 1 << 0
	attrUnderline = 1 << 1
	attrBold      = 1 << 2
)

func Render(view vt10x.View, layer string, control bool) []byte {
	frame := make([]byte, FrameBytes)
	view.Lock()
	cursor := view.Cursor()
	cursorVisible := view.CursorVisible()
	for row := 0; row < Rows; row++ {
		for column := 0; column < Columns; column++ {
			glyph := view.Cell(column, row)
			inverse := glyph.Mode&attrReverse != 0 ||
				(glyph.BG != vt10x.DefaultBG && glyph.BG != vt10x.Black)
			if cursorVisible && cursor.X == column && cursor.Y == row {
				inverse = !inverse
			}
			drawCell(frame, column*6, row*8, glyph.Char, inverse,
				glyph.Mode&attrUnderline != 0, glyph.Mode&attrBold != 0)
		}
	}
	view.Unlock()

	footer := fmt.Sprintf("SH:%-3s OK:CTRL HOME:EXIT", layer)
	if control {
		footer = fmt.Sprintf("SH:%-3s OK:CTRL* HOME:EXIT", layer)
	}
	drawTextRow(frame, Rows*8, footer)
	return frame
}

func drawTextRow(frame []byte, y int, text string) {
	for column, character := range text {
		if column >= Columns {
			break
		}
		drawCell(frame, column*6, y, character, false, false, false)
	}
}

func setPixel(frame []byte, x, y int, black bool) bool {
	if len(frame) != FrameBytes || x < 0 || x >= Width || y < 0 || y >= Height {
		return false
	}
	offset := (y/stripHeight)*Width + x
	mask := byte(0x80 >> (y % stripHeight))
	if black {
		frame[offset] |= mask
	} else {
		frame[offset] &^= mask
	}
	return true
}

func fillCell(frame []byte, x, y int, black bool) {
	for column := 0; column < 6; column++ {
		for row := 0; row < 8; row++ {
			setPixel(frame, x+column, y+row, black)
		}
	}
}

func drawCell(frame []byte, x, y int, character rune, inverse, underline, bold bool) {
	bits := glyph(character)
	fillCell(frame, x, y, inverse)
	for column := 0; column < 5; column++ {
		for row := 0; row < 7; row++ {
			set := bits[column]&(1<<row) != 0
			if underline && row == 6 {
				set = true
			}
			if set {
				setPixel(frame, x+column, y+row, !inverse)
				if bold && column+1 < 5 {
					setPixel(frame, x+column+1, y+row, !inverse)
				}
			}
		}
	}
}

func glyph(character rune) [5]byte {
	switch character {
	case '─', '━', '⎺', '⎻', '⎼', '⎽':
		character = '-'
	case '│', '┃':
		character = '|'
	case '┌', '┐', '└', '┘', '├', '┤', '┬', '┴', '┼':
		character = '+'
	case 0:
		character = ' '
	}
	if character >= 0x20 && character <= 0x7e {
		return terminalFont[character-0x20]
	}
	return [5]byte{0x7f, 0x41, 0x5d, 0x41, 0x7f}
}

